// Turns Japanese subtitle files into tap-to-learn reels.
//
//   npx tsx scripts/import-subtitles.ts scripts/reels.json
//
// reels.json is a list of { videoId, title, channel, level, start?, end?, subtitles, translations? }
// where `subtitles` is a WebVTT (.vtt) file of Japanese captions, and the optional `translations`
// is a .vtt file of English captions with the same timings.
// Only add videos whose captions you are allowed to use, and keep the channel credit.
import fs from 'node:fs';
import path from 'node:path';
import kuromoji from 'kuromoji';

type Spec = { videoId: string; title: string; channel: string; level: string; start?: number; end?: number; subtitles: string; translations?: string };
type Cue = { start: number; end: number; text: string };

const POS: Record<string, string> = {
  名詞: 'noun', 動詞: 'verb', 形容詞: 'adjective', 形容動詞: 'na-adjective', 助詞: 'particle', 助動詞: 'auxiliary',
  副詞: 'adverb', 連体詞: 'pre-noun', 接続詞: 'conjunction', 感動詞: 'interjection', 接頭詞: 'prefix', フィラー: 'filler', 記号: 'symbol',
};

function toSeconds(t: string) {
  const parts = t.trim().replace(',', '.').split(':').map(Number);
  return parts.reduce((acc, n) => acc * 60 + n, 0);
}

export function parseVtt(src: string): Cue[] {
  const cues: Cue[] = [];
  for (const block of src.replace(/\r/g, '').split(/\n\n+/)) {
    const lines = block.split('\n').filter(Boolean);
    const timing = lines.findIndex((l) => l.includes('-->'));
    if (timing === -1) continue;
    const [a, b] = lines[timing].split('-->');
    const text = lines
      .slice(timing + 1)
      .join(' ')
      .replace(/<[^>]+>/g, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (!text) continue;
    const cue = { start: toSeconds(a), end: toSeconds(b.split(' ').filter(Boolean)[0]), text };
    // auto-generated captions repeat the previous line; skip exact repeats
    if (cues.length && cues[cues.length - 1].text === text) cues[cues.length - 1].end = cue.end;
    else cues.push(cue);
  }
  return cues;
}

const kata2hira = (s: string) => s.replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));

async function main() {
  const specPath = process.argv[2];
  if (!specPath) throw new Error('usage: tsx scripts/import-subtitles.ts <reels.json>');
  const specs: Spec[] = JSON.parse(fs.readFileSync(specPath, 'utf8'));
  const base = path.dirname(specPath);
  const tokenizer = await new Promise<kuromoji.Tokenizer<kuromoji.IpadicFeatures>>((res, rej) =>
    kuromoji.builder({ dicPath: path.join('node_modules', 'kuromoji', 'dict') }).build((err, t) => (err ? rej(err) : res(t))),
  );

  const reels = specs.map((spec) => {
    const ja = parseVtt(fs.readFileSync(path.join(base, spec.subtitles), 'utf8'));
    const en = spec.translations ? parseVtt(fs.readFileSync(path.join(base, spec.translations), 'utf8')) : [];
    const lines = ja.map((cue) => {
      const tokens = tokenizer.tokenize(cue.text).map((t) => {
        const tok: { s: string; r?: string; b?: string; p?: string } = { s: t.surface_form, p: POS[t.pos] ?? t.pos };
        if (t.reading && t.reading !== '*') tok.r = kata2hira(t.reading);
        if (t.basic_form && t.basic_form !== '*' && t.basic_form !== t.surface_form) tok.b = t.basic_form;
        return tok;
      });
      const mid = (cue.start + cue.end) / 2;
      const tr = en.find((e) => mid >= e.start && mid <= e.end);
      return { start: cue.start, end: cue.end, tokens, ...(tr ? { en: tr.text } : {}) };
    });
    const { subtitles, translations, ...meta } = spec;
    return { id: `yt-${spec.videoId}`, ...meta, lines };
  });

  const out = `// Generated by scripts/import-subtitles.ts. Do not edit by hand.\nimport type { Reel } from './reels';\n\nexport const GENERATED_REELS: Reel[] = ${JSON.stringify(reels, null, 1)};\n`;
  fs.writeFileSync('src/data/reels.generated.ts', out);
  console.log(`Wrote ${reels.length} reel(s), ${reels.reduce((a, r) => a + r.lines.length, 0)} subtitle lines`);
}

if (process.argv[1]?.endsWith('import-subtitles.ts')) main().catch((e) => { console.error(e); process.exit(1); });
